"""Write preregistration attachments 4 (first half), 5 and 6 from the freeze commit (docs/preregistration-draft.md, "添付の一覧").

Every file is read from the commit with `git show <commit>:<path>`, not from the working tree.
  A4-frozen-set.md   the freeze commit and the sha256 of each file of the frozen set (the FROZEN array of
                     experiments/_confirm-template/e1/run.sh at that commit), of the registered documents and of attachments
                     1-3, 7, 8. The second half (cohort manifests) is added after generation, before E1 and E2 are run.
  A5-seeds.md        the 10 seeds, as written in docs/preregistration-en.md (Data collection procedures) at that commit
  A6-run-sh-e1.sh, A6-run-sh-e2.sh   the confirmatory run.sh templates as frozen (the fields filled after the freeze are
                     added to the OSF project before each run)

Usage: python scripts/prereg_freeze_attachments.py <freeze-commit> <out-dir>
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ["docs/preregistration-en.md", "docs/preregistration-draft.md"]
ATT = ["docs/prereg-attachments/A1-models.md", "docs/prereg-attachments/A2-prompts.md",
       "docs/prereg-attachments/A3-paraphrases.md", "docs/prereg-attachments/A7-sample-size.md",
       "docs/prereg-attachments/A8-foreknowledge-values.md", "scripts/prereg_attachments.py"]


def git(*args: str) -> bytes:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, check=True).stdout


def blob(commit: str, path: str) -> bytes:
    return git("show", f"{commit}:{path}")


def frozen_list(commit: str) -> list[str]:
    sh = blob(commit, "experiments/_confirm-template/e1/run.sh").decode()
    body = re.search(r"^FROZEN=\((.*?)^\)", sh, re.S | re.M).group(1)
    return body.split()


def table(commit: str, paths: list[str]) -> list[str]:
    out = ["| File | sha256 |", "|---|---|"]
    for p in paths:
        out.append(f"| `{p}` | `{hashlib.sha256(blob(commit, p)).hexdigest()}` |")
    return out


def main(commit: str, out: Path) -> None:
    full = git("rev-parse", commit).decode().strip()
    when = git("show", "-s", "--format=%cI", full).decode().strip()
    out.mkdir(parents=True, exist_ok=True)
    frozen = frozen_list(full)
    a4 = ["# Attachment 4 — Freeze commit and sha256 of the frozen set (first half)\n",
          f"Freeze commit: `{full}` (git, committed {when}). Generated by `scripts/prereg_freeze_attachments.py {full[:7]}`, "
          "which reads every file from that commit (`git show <commit>:<path>`).\n",
          "Check: `git show <commit>:<path> | sha256sum`. The confirmatory `run.sh` refuses to run unless each of these files "
          "equals the freeze commit and no untracked files are in `scripts/` or `tests/`.\n",
          f"## Frozen set ({len(frozen)} files; the `FROZEN` array of `experiments/_confirm-template/e1/run.sh`)\n",
          *table(full, frozen), "",
          "## Registered documents (not part of the frozen set; recorded for reference)\n",
          *table(full, DOCS), "",
          "## Attachments 1–3, 7, 8 and the script that writes 1–3\n",
          *table(full, ATT), "",
          "## Second half (added after the cohort is generated, before E1 and E2 are run)\n",
          "The manifests of the 4 shards of the confirmatory cohort (each with `contentSha256`, `pjCommit` = the freeze commit, "
          "`profileCohortSha256`) and the merge manifest are uploaded to the same OSF project with a timestamp before any "
          "confirmatory E1 or E2 run.\n"]
    en = blob(full, "docs/preregistration-en.md").decode()
    seeds = [line for line in en.splitlines() if re.match(r"\s*- (Cohort seeds|E1 seed|E2 seed)", line)]
    assert len(seeds) == 3 and "___" not in "".join(seeds), seeds
    a5 = ["# Attachment 5 — Seeds\n",
          f"As written in `docs/preregistration-en.md` (Data collection procedures) at the freeze commit `{full}`:\n",
          *seeds, ""]
    files = {"A4-frozen-set.md": "\n".join(a4), "A5-seeds.md": "\n".join(a5)}
    for k in ("e1", "e2"):
        files[f"A6-run-sh-{k}.sh"] = blob(full, f"experiments/_confirm-template/{k}/run.sh").decode()
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
        print(out / name)


if __name__ == "__main__":
    main(sys.argv[1], Path(sys.argv[2]))

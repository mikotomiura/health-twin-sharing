"""Write preregistration attachments 1-3 (docs/preregistration-draft.md, "添付の一覧") from the code itself.

  A1-models.md       model names, digests and Ollama version fixed in experiments/_confirm-template/e1/run.sh, the model
                     options of config/e1_confirm.json, and the digests observed in the last Colab run
  A2-prompts.md      the full prompts. Not copied by hand: scripts/e1_run.py runs every stage on a tiny experiment (1 A and
                     1 non-A person of the development cohort, config/e1_confirm.json otherwise) with a fake model that
                     records each request; the requests of one cell are printed verbatim
  A3-paraphrases.md  paraphrases 0-7 of config/e1_confirm.json

Usage: uv run --frozen python scripts/prereg_attachments.py <derived-dir> <out-dir>
  <derived-dir>: the development cohort's parquet (e.g. $HTS_DATA_DIR/derived/cohort-10k). Not part of the frozen set.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import e1_run  # noqa: E402
from llm_dry_run_attacker import PCT_SCHEMA, FakePct  # noqa: E402
from llm_dry_run_extra import UTIL_SCHEMA  # noqa: E402

DEV_SEED = "1956235754"  # development seed (that of experiments/20261113-e1-novisits-check); the persons are only examples
CONFIG = ROOT / "config/e1_confirm.json"
RUN_SH = ROOT / "experiments/_confirm-template/e1/run.sh"
VERSIONS = ROOT / "experiments/20261114-e1-numctx-check/results/versions.jsonl"
FENCE = "````"

CURRENT: dict = {}
CALLS: list[dict] = []


class Recorder(FakePct):
    def chat(self, model, messages, seed, options, fmt=None):
        CALLS.append({**CURRENT, "model": model, "messages": json.loads(json.dumps(messages)), "seed": seed,
                      "format": "PCT_SCHEMA" if fmt is PCT_SCHEMA else "UTIL_SCHEMA" if fmt is UTIL_SCHEMA else None})
        return super().chat(model, messages, seed, options, fmt)


def run_jobs_tagged(jobs, fn, workers, label):
    for j in jobs:  # sequential, so every request is tagged with its stage and job
        CURRENT.clear()
        CURRENT.update(stage=label, job=j)
        fn(j)


def git_head() -> str:
    return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()


def code_block(text: str) -> str:
    assert FENCE not in text
    return f"{FENCE}text\n{text}\n{FENCE}"


def show_call(c: dict) -> str:
    out = [f"- model `{c['model']}`, format {c['format'] or 'none (free text)'}, seed in this example {c['seed']}"]
    for m in c["messages"]:
        out.append(f"\n**{m['role']}**\n\n{code_block(m['content'])}")
    return "\n".join(out)


def build_example(derived: Path, tmp: Path) -> e1_run.Exp:
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    cfg["n_A"] = cfg["n_not_A"] = 1
    cfg["_note"] = "attachment example: config/e1_confirm.json with n_A = n_not_A = 1 (development cohort)"
    (tmp / "config.json").write_text(json.dumps(cfg, indent=1, ensure_ascii=False), encoding="utf-8")
    (tmp / "SEED").write_text(DEV_SEED + "\n")
    subprocess.run([sys.executable, str(ROOT / "scripts/e1_build.py"), str(derived), str(tmp)], check=True,
                   stdout=subprocess.DEVNULL)
    return e1_run.Exp(tmp)


def a2(x: e1_run.Exp, head: str) -> str:
    e1_run.run_jobs = run_jobs_tagged
    be, skips = Recorder(), e1_run.Skips()
    e1_run.stage_twin(x, be, 1)
    e1_run.stage_attack(x, be, 1, skips)
    e1_run.stage_calib(x, be, 1, skips)
    e1_run.stage_utility(x, be, 1, skips)
    assert skips.n == 0
    cfg = x.cfg
    pid_a = next(pid for (pid, lam, d), r in sorted(x.rows.items()) if r["A"] and lam == 1 and d == "D0")
    cell = (pid_a, 1, "D0", 0, 0)

    def pick(stage, pred):
        got = [c for c in CALLS if c["stage"] == stage and pred(c["job"])]
        assert got, (stage,)
        return got

    twin = pick("twin", lambda j: j == cell)
    assert len(twin) == len(cfg["years"])
    attack = {kk: pick("attack", lambda j, kk=kk: j[1] == ("t3", kk, cell))[0] for kk in cfg["knowledge_levels"]}
    attack_t0 = pick("attack", lambda j: j[1] == ("t0", "K2", pid_a, 1))[0]
    calib = pick("calib", lambda j: j == (1, cell))[0]
    util = pick("utility", lambda j: j[0] == cell and j[1] == len(cfg["years"]))[0]

    s = [f"# Attachment 2 — Full prompts (E1)\n",
         f"Generated by `scripts/prereg_attachments.py` at commit `{head}`. The requests below are those that "
         "`scripts/e1_run.py` sent, recorded verbatim, when every stage ran on a tiny example experiment "
         "(`config/e1_confirm.json` with 1 A and 1 non-A person of the **development** cohort, development seed "
         f"{DEV_SEED}) against a fake model. Therefore:\n",
         "- the record, the person's age and gender, and the rates in the K1 and K2 sentences are those of the "
         "development cohort (an example of the form). In the confirmatory run the rates are recomputed on the "
         "confirmatory cohort (population minus the E1 persons, per λ);",
         "- the agent's answers inside later requests (conversation history, `[Release n]`) are the fake model's "
         "placeholder text, not real answers;",
         "- the seeds shown are those of the example; the confirmatory seeds follow Data collection procedures "
         "(agent = E1 seed + 1000 × seed index, attacker = E1 seed + 7, judge = E1 seed + 11).\n",
         f"Example cell: an A person, λ = 1, D0, paraphrase 0, agent seed index 0. {len(CALLS)} requests were recorded "
         "in all.\n",
         "## Model options (`config/e1_confirm.json`)\n",
         code_block(json.dumps({k: cfg[k] for k in ("twin_model", "twin_options", "attacker_model", "attacker_options",
                                                       "judge_model", "judge_options", "attacker_template",
                                                       "max_retries")}, indent=1)),
         "\n## JSON schemas (Ollama `format`)\n",
         "Attacker (PCT_SCHEMA):\n", code_block(json.dumps(PCT_SCHEMA, indent=1)),
         "\nJudge (UTIL_SCHEMA):\n", code_block(json.dumps(UTIL_SCHEMA, indent=1)),
         "\n## 1. Agent (the twin): the requests at t1, t2, t3 of one cell\n",
         "The request at time point t carries the conversation so far (earlier user turns and the agent's earlier "
         "answers).\n"]
    for t, c in enumerate(twin, 1):
        s += [f"### t{t}\n", show_call(c), ""]
    s += ["## 2. Attacker at t3, one request per knowledge level (same cell)\n",
          "K0 = age and gender; K1 = K0 + the population rate; K2 = K1 + the rates given each D2 display and group; "
          "K3 = K2 + whether this person has each D2 display; K0n = K0 + a neutral text as long as the K1 and K2 "
          "sentences.\n"]
    for kk, c in attack.items():
        s += [f"### {kk}\n", show_call(c), ""]
    s += ["## 3. Attacker at t0 (no releases), K2\n", show_call(attack_t0), "",
          "## 4. H0b calibration (label sentence appended to the last release), q = 1\n", show_call(calib), "",
          "## 5. Judge (utility), t3 of the same cell\n",
          "The judge sees the full record of that year (before the defender's changes) and the agent's answer.\n",
          show_call(util), ""]
    return "\n".join(s)


def a1(head: str) -> str:
    sh = RUN_SH.read_text(encoding="utf-8")
    val = {k: re.search(rf'^{k}="([^"]*)"', sh, re.M).group(1) for k in ("DIGEST_AGENT", "DIGEST_ATTACKER", "OLLAMA_VERSION")}
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    seen = [json.loads(line) for line in VERSIONS.read_text().splitlines() if line.strip()]
    return "\n".join([
        "# Attachment 1 — Models and Ollama version\n",
        f"Generated by `scripts/prereg_attachments.py` at commit `{head}` from "
        "`experiments/_confirm-template/e1/run.sh` and `config/e1_confirm.json`.\n",
        "| Role | Model | Digest (`/api/tags`) |", "|---|---|---|",
        f"| Agent (twin) | `{cfg['twin_model']}` | `{val['DIGEST_AGENT']}` |",
        f"| Attacker | `{cfg['attacker_model']}` | `{val['DIGEST_ATTACKER']}` |",
        f"| Judge | `{cfg['judge_model']}` | `{val['DIGEST_ATTACKER']}` |", "",
        f"Ollama version: `{val['OLLAMA_VERSION']}`, installed on Colab with "
        f"`curl -fsSL https://ollama.com/install.sh | OLLAMA_VERSION={val['OLLAMA_VERSION']} sh`.\n",
        "`scripts/e1_run.py` compares the live digests and Ollama version with these values before any model call, on "
        "every start (first run and every resume), and stops if they differ (`--expect-digests`, `--expect-ollama`). "
        "The values observed in each confirmatory run are written to `results/versions.jsonl` and reported.\n",
        "These digests were checked on 2026-11-14 against the Colab run records and the manifests of "
        "registry.ollama.ai, and will be checked again just before the freeze. Last observed values "
        "(`experiments/20261114-e1-numctx-check/results/versions.jsonl`, Colab L4, development run):\n",
        code_block("\n".join(json.dumps(v) for v in seen)), ""])


def a3(head: str) -> str:
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    b = cfg["base_point"]
    s = ["# Attachment 3 — Paraphrases 0–7 of the user's request\n",
         f"Generated by `scripts/prereg_attachments.py` at commit `{head}` from `config/e1_confirm.json` "
         "(`paraphrases`). `{recipient}` and `{question}` are filled from `recipient` "
         f"(name: {cfg['recipient']['name']!r}; question: {cfg['recipient']['question']!r}).\n",
         f"Paraphrases 0–{cfg['n_paraphrases_default'] - 1} are used in every cell; all "
         f"{b['n_paraphrases']} are used at the base point (λ = {b['lambda']}, {b['D']}; attacker levels "
         f"{', '.join(b['K'])}) for H3.\n"]
    for i, p in enumerate(cfg["paraphrases"]):
        s += [f"## Paraphrase {i}\n", code_block(p), ""]
    return "\n".join(s)


def main(derived: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    head = git_head()
    tmp = Path(tempfile.mkdtemp(prefix="prereg-att-"))
    try:
        x = build_example(derived, tmp)
        files = {"A1-models.md": a1(head), "A2-prompts.md": a2(x, head), "A3-paraphrases.md": a3(head)}
    finally:
        shutil.rmtree(tmp)
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
        print(out / name)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
